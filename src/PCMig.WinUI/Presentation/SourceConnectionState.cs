namespace PCMig.WinUI.Presentation;

/// <summary>
/// PCMig 当前**源共享连接状态**（★ 2026-10-08 真机问题 4 ★）。
///
/// 【为什么需要它】改前底栏那颗点是硬编码的 <c>Fill="{StaticResource SuccessBrush}"</c> ——
/// 无论有没有连上旧电脑、有没有可访问的共享，它永远是绿的，等于没有信息量。
/// 它当时唯一说得通的解释是"Windows 有没有互联网"，而那不是 PCMig 该表达的事。
/// 它现在表达的唯一事实是：**PCMig 到旧电脑的 SMB 源共享是否可用**（不是 ICMP、不是网卡 UP、不是能上网）。
///
/// 【状态源纪律】本枚举由 <c>ConnectionViewModel</c> 拥有并**单点派生**（见其 <c>UpdateSourceState</c>），
/// View 只投影、绝不自己猜（原有缺陷的根因就是"View 里写死了一个颜色"）。
/// </summary>
public enum SourceConnectionState
{
    /// <summary>
    /// 未连接 / 连接失败 / 运行中源失效 / 没有任何已验证可访问的源共享。
    /// 表现：底栏指示灯**常亮红色，不闪烁**。
    /// </summary>
    Disconnected,

    /// <summary>
    /// 正在连接 / 正在探测：点击"连接并列出共享"、WNet 建立 SMB 会话、枚举共享、验证手工共享。
    /// 表现：底栏指示灯**琥珀色柔和呼吸**（Composition 动画，不是生硬的开/关闪烁）。
    /// </summary>
    Connecting,

    /// <summary>
    /// 至少存在一个**当前已验证可访问**的源共享（= 可读探测确认过，不是"上次连上过"）。
    /// 表现：底栏指示灯**稳定常亮绿色**。
    /// </summary>
    Connected,

    /// <summary>
    /// ★ 真机问题 1（2026-10-21）★ **已连接且确有数据传输正在进行**。
    ///
    /// 【为什么必须与 Connected 分开】现场症状：传输跑到 93.3%、当前文件列表有内容，
    /// 底栏「源连接」却是**黄色**。原因是旧模型只有"连上/没连上"，且可达证据有 60 秒有效期，
    /// 传输期间没有任何代码续期 ⇒ 证据一过期就掉成 <see cref="SuspectOrUnknown"/>（琥珀）。
    /// 用户看到"黄灯"会以为连接有问题，而实际上正在飞速传输。
    ///
    /// 【判据纪律】本状态只能由**真实字节增长**驱动（引擎进度快照里已显示字节确实变大），
    /// 绝不允许仅凭 <c>Phase == Running</c> 或"上一次非零速度"点亮 —— 那是假活动。
    /// 表现：绿色**呼吸**（与 Connecting 同族动效，但颜色是成功色）。
    /// </summary>
    Transferring,

    /// <summary>
    /// ★ P0-05 ★ **部分可用**：多共享里至少一条被确认可达、同时至少一条被确认失效。
    /// 这是现场最常见的一种真实状态（\\host\C 还在、\\host\D 被策略关掉），旧的三态模型里它无处安放，
    /// 只能被迫显示成绿的。表现：琥珀色常亮 + 底栏写清是哪一条失效。
    /// </summary>
    Partial,

    /// <summary>
    /// ★ P0-05 ★ **存疑 / 未知**：手上没有任何"源共享现在读得到"的证据（只有历史连接事实、
    /// 或者收到的信号自相矛盾）。★ 关键纪律：未知**绝不能**显示成绿色 ★ ——
    /// 用户看到绿的含义必须是"刚刚确认过能读"，而不是"曾经连上过"。
    /// 表现：琥珀色常亮。
    /// </summary>
    SuspectOrUnknown,

    /// <summary>
    /// ★ P0-05 ★ **恢复中**：已确认失效、正在等待/执行可读探测（重连、重新枚举共享、重试验证）。
    /// 它不是绿也不是红：说明"我知道它坏了，正在查"。表现：琥珀色柔和呼吸（与 Connecting 同族动效）。
    /// </summary>
    Recovering,
}